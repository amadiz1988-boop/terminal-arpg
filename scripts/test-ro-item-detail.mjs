// Every indexed asset must exist on disk with a matching provenance hash.
const assetProblems = [];
for (const entry of all) {
  for (const [role, asset] of [['icon', entry.icon], ['collectionArt', entry.collectionArt], ['cardArt', entry.cardArt]]) {
    if (!asset) continue;
    if (!asset.webPath || !existsSync(webFile(asset.webPath))) {
      assetProblems.push(`${entry.itemId}:${role}:missing-file`);
      continue;
    }
    if (asset.webSha256 && sha256(webFile(asset.webPath)) !== asset.webSha256) assetProblems.push(`${entry.itemId}:${role}:hash`);
    if (!asset.sourceSha256 || asset.sourceSha256.length !== 64) assetProblems.push(`${entry.itemId}:${role}:source-hash`);
  }
}
check('all indexed web assets exist and hashes verify', assetProblems.length === 0, assetProblems.slice(0, 3).join(','));

// item/ and collection/ must be distinct original files sharing ResourceName.
const separation = [];
for (const entry of collectionEntries) {
  if (!entry.icon) continue;
  if (entry.icon.sourcePath === entry.collectionArt.sourcePath) separation.push(`${entry.itemId}:same-source`);
  if (entry.icon.sourceSha256 === entry.collectionArt.sourceSha256) separation.push(`${entry.itemId}:same-source-hash`);
  if (entry.icon.webPath === entry.collectionArt.webPath) separation.push(`${entry.itemId}:same-web`);
  if (entry.icon.webSha256 && entry.icon.webSha256 === entry.collectionArt.webSha256) separation.push(`${entry.itemId}:same-web-hash`);
}
check('inventory icon != collection art for every item that has both', separation.length === 0, separation.slice(0, 3).join(','));

// ResourceName mapping authority: both families share one identifiedResourceName.
const mappingProblems = [];
for (const entry of collectionEntries) {
  const record = provenanceByItemId.get(Number(entry.itemId));
  if (!record) { mappingProblems.push(`${entry.itemId}:no-provenance`); continue; }
  const resource = record.resourceName;
  const collectionBase = String(entry.collectionArt.sourcePath).split(/[\\/]/).at(-1);
  if (collectionBase !== resource) mappingProblems.push(`${entry.itemId}:collection-name`);
  if (entry.icon) {
    const iconBase = String(entry.icon.sourcePath).split(/[\\/]/).at(-1);
    if (iconBase !== resource) mappingProblems.push(`${entry.itemId}:icon-name`);
  }
  if (entry.collectionArt.sourceSha256 !== record.collection?.sourceSha256) mappingProblems.push(`${entry.itemId}:provenance-hash`);
}
check(
  'item/ and collection/ share the authoritative identifiedResourceName',
  mappingProblems.length === 0,
  mappingProblems.slice(0, 3).join(','),
);

