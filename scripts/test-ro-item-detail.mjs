/**
 * RO Item Detail (RoItemDetail) targeted gate.
 *
 * Verifies that the shared inventory/equipment detail renderer presents the
 * original RO description art family (collection/) ahead of the inventory icon
 * family (item/), keeps the two families distinct, keeps card illustration
 * behavior intact, and never invents item facts.
 *
 * Usage: node scripts/test-ro-item-detail.mjs
 * Exit 0 = PASS, Exit 1 = FAIL
 */

