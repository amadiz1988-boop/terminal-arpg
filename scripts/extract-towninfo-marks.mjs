// Extracts the original client town minimap marks (System/Towninfo.lub,
// mapNPCInfoTable) into ops/ro-stack/dashboard/towninfo-marks.mjs.
// Towninfo.lub is Lua 5.1 bytecode holding only table constructors, so a tiny
// interpreter for the opcodes it uses is enough; anything else aborts.
//   node scripts/extract-towninfo-marks.mjs [--client <RO client dir>]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argIndex = process.argv.indexOf('--client');
const client = argIndex > 0 ? process.argv[argIndex + 1]
  : process.env.RO_CLIENT_DIR ?? 'C:\\Program Files (x86)\\Gravity\\RagnarokOnline';
const sourcePath = join(client, 'System', 'Towninfo.lub');
const outputPath = join(root, 'ops', 'ro-stack', 'dashboard', 'towninfo-marks.mjs');

const bytes = readFileSync(sourcePath);
const sha256 = createHash('sha256').update(bytes).digest('hex');
if (bytes.subarray(0, 4).toString('latin1') !== '\x1bLua' || bytes[4] !== 0x51)
  throw new Error('Towninfo.lub is not Lua 5.1 bytecode');

let offset = 12;
const u8 = () => bytes[offset++];
const u32 = () => { const value = bytes.readUInt32LE(offset); offset += 4; return value; };
const f64 = () => { const value = bytes.readDoubleLE(offset); offset += 8; return value; };
const decode = (buffer) => {
  for (const encoding of ['utf-8', 'big5', 'euc-kr']) {
    try { return new TextDecoder(encoding, { fatal: true }).decode(buffer); } catch {}
  }
  // Non-text constants (outside mapNPCInfoTable) stay tagged; mark names must decode.
  return '\u0000' + buffer.toString('latin1');
};
const string = () => {
  const length = u32();
  if (!length) return null;
  const value = decode(bytes.subarray(offset, offset + length - 1));
  offset += length;
  return value;
};
function proto() {
  const p = {};
  string(); u32(); u32();
  p.upvalues = u8(); u8(); u8(); u8();
  p.code = Array.from({ length: u32() }, u32);
  p.k = Array.from({ length: u32() }, () => {
    const type = u8();
    if (type === 0) return null;
    if (type === 1) return u8() !== 0;
    if (type === 3) return f64();
    if (type === 4) return string();
    throw new Error(`Unsupported constant type ${type}`);
  });
  p.protos = Array.from({ length: u32() }, proto);
  const lineInfo = u32();
  offset += lineInfo * 4;
  for (let i = u32(); i > 0; i -= 1) { string(); u32(); u32(); }
  for (let i = u32(); i > 0; i -= 1) string();
  return p;
}

const globals = {};
function run(p) {
  const R = [];
  const RK = (x) => (x & 256 ? p.k[x & 255] : R[x]);
  for (let pc = 0; pc < p.code.length;) {
    const i = p.code[pc++];
    const op = i & 63, A = (i >>> 6) & 255, C = (i >>> 14) & 511, B = (i >>> 23) & 511, Bx = i >>> 14;
    const sBx = Bx - 131071;
    switch (op) {
      case 0: R[A] = R[B]; break;
      case 1: R[A] = p.k[Bx]; break;
      case 2: R[A] = B !== 0; if (C) pc += 1; break;
      case 3: for (let r = A; r <= B; r += 1) R[r] = null; break;
      case 5: R[A] = globals[p.k[Bx]]; break;
      case 6: R[A] = R[B]?.[RK(C)]; break;
      case 7: globals[p.k[Bx]] = R[A]; break;
      case 9: R[A][RK(B)] = RK(C); break;
      case 10: R[A] = {}; break;
      case 12: R[A] = RK(B) + RK(C); break;
      case 13: R[A] = RK(B) - RK(C); break;
      case 18: R[A] = -R[B]; break;
      case 22: pc += sBx; break;
      case 34: { // SETLIST
        const block = C === 0 ? p.code[pc++] : C;
        for (let j = 1; j <= B; j += 1) R[A][(block - 1) * 50 + j] = R[A + j];
        break;
      }
      case 36: R[A] = { closure: true }; pc += p.protos[Bx].upvalues; break;
      case 30: return;
      default: throw new Error('Unsupported opcode ' + op);
    }
  }
}
run(proto());

const table = globals.mapNPCInfoTable;
if (!table || typeof table !== 'object') throw new Error('mapNPCInfoTable missing');
const marks = {};
for (const [map, entries] of Object.entries(table)) {
  marks[map] = Object.keys(entries).map(Number).sort((a, b) => a - b).map((index) => {
    const entry = entries[index];
    const mark = { name: entry.name, x: entry.X, y: entry.Y, type: entry.TYPE };
    if (typeof mark.name !== 'string' || mark.name.startsWith('\u0000') ||
      ![mark.x, mark.y, mark.type].every(Number.isInteger))
      throw new Error('Invalid mark ' + map + '#' + index);
    return mark;
  });
}

const markLine = (m) => '    { name: ' + JSON.stringify(m.name) + ', x: ' + m.x + ', y: ' + m.y + ', type: ' + m.type + ' },';
writeFileSync(outputPath, [
  '// Generated by scripts/extract-towninfo-marks.mjs. Do not edit by hand.',
  '// Original client town minimap marks: System/Towninfo.lub mapNPCInfoTable,',
  '// in client order. TYPE maps to an information icon (see town-service-zones.mjs).',
  "export const TOWNINFO_SOURCE = Object.freeze({ path: 'System/Towninfo.lub', sha256: '" + sha256 + "' });",
  '',
  'export const TOWNINFO_MARKS = {',
  ...Object.entries(marks).flatMap(([map, list]) => ['  ' + map + ': [', ...list.map(markLine), '  ],']),
  '};',
  'for (const list of Object.values(TOWNINFO_MARKS)) { list.forEach(Object.freeze); Object.freeze(list); }',
  'Object.freeze(TOWNINFO_MARKS);',
  '',
].join('\n'));
const count = Object.values(marks).reduce((sum, list) => sum + list.length, 0);
console.log(JSON.stringify({ result: 'TOWNINFO_MARKS_EXTRACTED', sha256, maps: Object.keys(marks).length, marks: count }));
